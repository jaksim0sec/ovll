import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const root=fileURLToPath(new URL('../../front/',import.meta.url));

test('composer keeps rich drafts safe, handles pickers and preserves rejected requests', async () => {
  const server=createServer(async(req,res)=>{
    if(req.url==='/fixture'){res.setHeader('Content-Type','text/html');res.end('<html lang="ko"><meta name="viewport" content="width=device-width"><link rel="stylesheet" href="/css/base.css"><link rel="stylesheet" href="/css/composer.css"><body><main style="position:fixed;bottom:20px;left:20px;right:20px;max-width:640px;margin:auto"></main></body></html>');return;}
    try{const file=await readFile(root+new URL(req.url,'http://localhost').pathname);res.setHeader('Content-Type',req.url.endsWith('.js')?'text/javascript':'text/css');res.end(file);}catch{res.writeHead(404);res.end();}
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  let browser;
  try{
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||(existsSync('/tmp/chromium')?'/tmp/chromium':undefined),args:['--no-sandbox','--disable-dev-shm-usage']});
  const page=await browser.newPage({viewport:{width:1000,height:800}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/fixture`);
    await page.evaluate(async()=>{
      const {createComposer}=await import('/js/composer/controller.js');
      window.submitted=[];
      const blocks=[{id:'b-1',skillId:'research',values:{}}];
      window.composer=createComposer({model:{getBlocks:()=>blocks,subscribe:()=>()=>{}},onSubmit: draft=>{window.submitted.push(draft);if(window.acceptNext)return {accepted:true};return {accepted:false,message:'아직 서버에 연결되지 않았습니다.'};}});
      document.querySelector('main').append(window.composer.element);window.composer.activate({});
    });
    const editor=page.getByRole('textbox',{name:'작업 입력'});
    assert.equal(await page.getByRole('button',{name:'빠른 명령',exact:true}).isVisible(),false);
    await editor.focus();
    await page.getByRole('button',{name:'빠른 명령',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'스킬 및 스킬블럭 참조',exact:true}).isVisible(),true);
    await editor.evaluate(node=>node.blur());
    await page.waitForFunction(()=>!document.querySelector('.ovll-composer-form').classList.contains('is-expanded'));
    await editor.focus();
    await page.evaluate(()=>window.composer.setDraft({parts:[{type:'text',text:'<img src=x onerror=alert(1)>'},{type:'skill',id:'research',label:'조사'},{type:'block',id:'b-1',label:'조사 블럭'}],attachments:[]}));
    assert.equal(await editor.locator('img').count(),0);
    assert.equal(await editor.locator('[data-ref-kind]').count(),2);
    const rich=await page.evaluate(()=>{const d=window.composer.getDraft();d.parts[1].label='mutated';return window.composer.getDraft();});
    assert.equal(rich.parts[1].label,'조사');
    await page.getByRole('button',{name:'요청 보내기',exact:true}).click();
    await page.getByRole('status').filter({hasText:'아직 서버'}).waitFor();
    assert.deepEqual(await page.evaluate(()=>window.composer.getDraft()),rich);
    await page.evaluate(()=>window.composer.setDraft({parts:[],attachments:[]}));
    await editor.fill('@');
    await page.getByRole('listbox').waitFor();
    assert.equal(await page.getByRole('option',{name:'시작하기',exact:false}).count(),0);
    await editor.press('ArrowDown');await editor.press('Enter');
    assert.equal(await editor.locator('[data-ref-kind="skill"]').count(),1);
    await editor.press('Backspace');
    assert.equal(await editor.locator('[data-ref-kind]').count(),0,await editor.evaluate(node=>JSON.stringify({html:node.innerHTML,anchor:document.getSelection().anchorNode?.nodeName,offset:document.getSelection().anchorOffset})));
    await editor.fill('/');await page.getByRole('listbox').waitFor();
    await editor.press('Escape');assert.equal(await page.getByRole('listbox').isVisible(),false);
    await editor.fill('한글');
    await editor.dispatchEvent('compositionstart');await editor.press('Enter');
    assert.equal(await page.evaluate(()=>window.submitted.length),1);
    await editor.dispatchEvent('compositionend');
    await page.evaluate(()=>window.composer.setDraft({parts:[{type:'text',text:'붙여넣기: '}],attachments:[]}));
    await editor.focus();await editor.press('End');
    await editor.evaluate(node=>{const data=new DataTransfer();data.setData('text/plain','<b>문자</b>');data.setData('text/html','<b>문자</b>');node.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}));});
    assert.equal(await editor.locator('b').count(),0);
    assert.match(await editor.innerText(),/<b>문자<\/b>/);
    assert.equal(await editor.evaluate(node=>{const data=new DataTransfer();data.setData('text/plain','드롭 문자');data.setData('text/html','<img src=x onerror=alert(1)>');return !node.dispatchEvent(new DragEvent('drop',{dataTransfer:data,bubbles:true,cancelable:true}));}),true);
    assert.equal(await editor.locator('img').count(),0);
    assert.match(await editor.innerText(),/드롭 문자/);
    await page.evaluate(()=>window.composer.setDraft({parts:[{type:'text',text:'a'.repeat(220)}],attachments:[]}));
    await page.waitForFunction(()=>document.querySelector('.ovll-composer-form').classList.contains('is-expanded'));
    await page.evaluate(()=>window.composer.setDraft({parts:[{type:'text',text:'짧게'}],attachments:[]}));
    await page.waitForFunction(()=>document.querySelector('.ovll-composer-form').classList.contains('is-expanded'));
    await editor.evaluate(node=>node.blur());
    assert.equal(await page.getByRole('button',{name:'빠른 명령',exact:true}).isVisible(),true);
    await page.getByRole('button',{name:'스킬블럭 참조',exact:true}).click();
    await page.getByRole('option',{name:'조사하기 1'}).click();
    assert.equal((await page.evaluate(()=>window.composer.getDraft())).parts.at(-2).type,'block');
    const tag=editor.locator('[data-ref-kind=block]');await tag.focus();
    await tag.press('Enter');await tag.press('Enter');
    assert.equal(await page.evaluate(()=>window.submitted.length),1);
    assert.equal(await editor.locator('[data-ref-kind]').count(),0);
    const chooserPromise=page.waitForEvent('filechooser');
    await page.getByRole('button',{name:'파일 추가',exact:true}).click();
    assert.equal(await page.getByRole('listbox').isVisible(),false);
    const chooser=await chooserPromise;
    await chooser.setFiles({name:'메모.txt',mimeType:'text/plain',buffer:Buffer.from('로컬 메모')});
    assert.equal(await page.getByRole('button',{name:'메모.txt 첨부 제거'}).isVisible(),true);
    assert.equal(await page.evaluate(async()=>{const d=window.composer.getDraft();const copy=structuredClone(d);window.composer.setDraft(copy);return await window.composer.getDraft().attachments[0].file.text();}),'로컬 메모');
    await page.getByRole('button',{name:'메모.txt 첨부 제거'}).click();
    assert.equal((await page.evaluate(()=>window.composer.getDraft())).attachments.length,0);
    await page.getByRole('button',{name:'빠른 명령',exact:true}).click();
    assert.equal(await page.getByRole('listbox').isVisible(),true);
    await page.evaluate(()=>window.composer.deactivate());
    assert.equal(await page.getByRole('listbox').isVisible(),false);
    await page.getByRole('button',{name:'빠른 명령',exact:true}).click();
    assert.equal(await page.getByRole('listbox').isVisible(),false);
    await page.evaluate(()=>{const controller=new AbortController();window.composer.activate({signal:controller.signal});window.leave=controller;});
    await page.getByRole('button',{name:'빠른 명령',exact:true}).click();
    await page.evaluate(()=>window.leave.abort());assert.equal(await page.getByRole('listbox').isVisible(),false);
    await page.setViewportSize({width:320,height:568});
    await page.evaluate(()=>window.composer.activate({}));
    await editor.focus();
    await page.getByRole('button',{name:'빠른 명령',exact:true}).click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await editor.evaluate(node=>getComputedStyle(node).fontSize),'14.6475px');
    assert.equal(await page.getByRole('button',{name:'스킬블럭 참조',exact:true}).isVisible(),false);
    await page.getByRole('button',{name:'스킬 및 스킬블럭 참조',exact:true}).click();
    assert.equal(await page.getByRole('option',{name:'조사하기 1',exact:false}).isVisible(),true);
    assert.deepEqual(errors,[]);
    await page.evaluate(()=>{window.composer.closeMenu();window.acceptNext=true;window.composer.setDraft({parts:[{type:'text',text:'명시적으로 수락한 요청'}],attachments:[]});});
    await page.getByRole('button',{name:'요청 보내기',exact:true}).click();
    assert.deepEqual(await page.evaluate(()=>window.composer.getDraft()),{parts:[],attachments:[]});
    await page.evaluate(()=>window.composer.destroy());
    const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    await mobile.goto(`http://127.0.0.1:${server.address().port}/fixture`);
    await mobile.evaluate(async()=>{const {createComposer}=await import('/js/composer/controller.js');window.sent=0;window.composer=createComposer({onSubmit:()=>{window.sent++;return {accepted:false};}});document.querySelector('main').append(window.composer.element);window.composer.activate({});});
    const mobileEditor=mobile.getByRole('textbox',{name:'작업 입력'});
    assert.equal(await mobileEditor.evaluate(node=>getComputedStyle(node).fontSize),'14.6475px');
    await mobileEditor.focus();
    await mobile.getByRole('button',{name:'빠른 명령',exact:true}).click();
    assert.equal(await mobileEditor.evaluate(node=>node===document.activeElement),false);
    assert.equal(await mobile.getByRole('listbox').isVisible(),true);
    assert.equal(await mobile.getByRole('button',{name:'스킬블럭 참조',exact:true}).isVisible(),true);
    await mobile.evaluate(()=>window.composer.closeMenu());
    await mobile.waitForFunction(()=>!document.querySelector('.ovll-composer-form').classList.contains('is-expanded'));
    await mobileEditor.focus();
    await mobileEditor.fill('첫 줄');await mobileEditor.press('Enter');
    assert.equal(await mobile.evaluate(()=>window.sent),0);
    await mobile.getByRole('button',{name:'빠른 명령',exact:true}).click();
    assert.equal(await mobileEditor.evaluate(node=>node===document.activeElement),false);
    await mobile.getByRole('option',{name:'스킬 참조',exact:false}).click();
    await mobile.getByRole('option',{name:'조사하기',exact:false}).click();
    assert.equal(await mobileEditor.locator('[data-ref-kind=skill]').count(),1);
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    if(process.env.COMPOSER_SCREENSHOT)await mobile.screenshot({path:process.env.COMPOSER_SCREENSHOT});
    await mobile.evaluate(()=>window.composer.destroy());
  }finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
});
