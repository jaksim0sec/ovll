import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {migrateWorkspaceToSkills} from '../front/js/ovllSkillWorkspaceMigration.mjs';
import {skillNodeSemanticFingerprint,isCurrentSkillNodeResult} from '../front/js/ovllPointerResults.mjs';
const fixtures=['workspace-node-v9.json','workspace-skill-v10.json'];
for(const name of fixtures)test('unchanged historical evidence survives native import: '+name,()=>{
  const original=JSON.parse(readFileSync(new URL('./fixtures/'+name,import.meta.url)));
  const before=structuredClone(original),migrated=migrateWorkspaceToSkills(original);
  const {skillGraph,skillRuns}=migrated.conversations[0].state,row=skillRuns[0].skillNodes[0];
  assert.equal(row.skillNodeId,'n_saved');
  assert.equal(row.semanticFingerprint,skillNodeSemanticFingerprint(skillGraph,'n_saved',row.semanticContext));
  assert.equal(isCurrentSkillNodeResult(skillGraph,'n_saved',row),true);
  const changed=structuredClone(skillGraph);changed.skillDefinitions[0].instruction='Different work';
  assert.equal(isCurrentSkillNodeResult(changed,'n_saved',row),false);
  assert.equal(isCurrentSkillNodeResult(skillGraph,'n_saved',{...row,skillNodeId:'forged'}),false);
  assert.equal(isCurrentSkillNodeResult(skillGraph,'n_saved',{...row,status:'pending'}),false);
  assert.deepEqual(skillGraph.graph.skillNodes[0].settings.payload,{nodeId:'opaque',skills:['opaque']});
  assert.deepEqual(original,before);
});
